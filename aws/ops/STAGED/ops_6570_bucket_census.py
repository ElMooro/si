"""ops 6570 - READ-ONLY full census of justhodl-dashboard-live, every key and every version, grouped by prefix.

Khalid, 2026-10-20 ("apply this one by one and make sure they work perfectly"): pieces 1 and 2 of the bucket design
need facts, not guesses - which prefixes are the warehouse (large, rarely rewritten, irreplaceable), which are the daily
churn (small, rewritten every day, regenerated by engines), and whether any prefix keeps more than 10 old versions of a
key as "history" (which the count-based expiry rule would cut).  ListObjectVersions over the whole bucket
(~5 M entries, ~5,000 LIST calls, < $0.05), walked in parallel by top-level prefix; data/ is split one level deeper.

Per prefix: current objects / bytes, noncurrent versions / bytes, delete markers, max versions on one key, keys with
> 10 old versions, bytes last modified > 7 and > 30 days ago (the low-churn share), largest object.  Full JSON to the
private bucket (census/<stamp>.json); the report names prefixes under data/ and the top-level ones - the bucket is
public and these are its public paths (ops 6544 withheld only private scopes; a prefix that contains 'private' or
'secret' is withheld here).
"""
from collections import defaultdict
from datetime import datetime, timedelta, timezone
from pathlib import Path
import concurrent.futures as cf
import json
import re
import sys
import time

import boto3
from botocore.config import Config

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "aws" / "ops"))
from ops_report import report  # noqa: E402

REGION, ACCOUNT = "us-east-1", "857687956942"
LIVE, PRIVATE = "justhodl-dashboard-live", "justhodl-ops-private-%s" % ACCOUNT
CFG = Config(retries={"max_attempts": 10, "mode": "standard"}, connect_timeout=10, read_timeout=120, max_pool_connections=40)
SENSITIVE = re.compile(r"private|secret|credential|token|password", re.I)


def gb(b):
    return round(b / 1024 ** 3, 2)


def label(p):
    return "WITHHELD" if SENSITIVE.search(p) else p


def top_prefixes(s3):
    """Top-level 'directories' plus data/<sub>/ one level down; root objects as ''."""
    out = []
    res = s3.list_objects_v2(Bucket=LIVE, Delimiter="/")
    for cp in res.get("CommonPrefixes", []):
        p = cp["Prefix"]
        if p == "data/":
            r2 = s3.list_objects_v2(Bucket=LIVE, Prefix="data/", Delimiter="/")
            out += [c["Prefix"] for c in r2.get("CommonPrefixes", [])]
            out.append("data/")          # the top-level files under data/ (walked with delimiter)
        else:
            out.append(p)
    if res.get("Contents"):
        out.append("")
    while res.get("IsTruncated"):      # more than 1,000 top-level entries (unlikely)
        res = s3.list_objects_v2(Bucket=LIVE, Delimiter="/", ContinuationToken=res["NextContinuationToken"])
        out += [c["Prefix"] for c in res.get("CommonPrefixes", [])]
    return sorted(set(out))


def walk(prefix, now):
    """Walk one prefix's versions.  'data/' and '' are walked with a delimiter (their own files only)."""
    s3 = boto3.client("s3", region_name=REGION, config=CFG)
    st = {"prefix": prefix, "current": 0, "current_bytes": 0, "noncurrent": 0, "noncurrent_bytes": 0, "markers": 0,
          "max_versions_key": 0, "keys_over_10": 0, "bytes_older_7d": 0, "bytes_older_30d": 0, "largest": ["", 0],
          "calls": 0, "sample_over_10": [], "by_day_bytes": defaultdict(int)}
    per_key = defaultdict(int)
    kw = {"Bucket": LIVE, "Prefix": prefix, "MaxKeys": 1000}
    if prefix in ("data/", ""):
        kw["Delimiter"] = "/"
    token = {}
    d7, d30 = now - timedelta(days=7), now - timedelta(days=30)
    deadline = time.time() + 2400
    while True:
        res = s3.list_object_versions(**kw, **token)
        st["calls"] += 1
        for v in res.get("Versions", []):
            size = v.get("Size", 0) or 0
            if v.get("IsLatest"):
                st["current"] += 1
                st["current_bytes"] += size
                lm = v.get("LastModified")
                if lm and lm < d7:
                    st["bytes_older_7d"] += size
                if lm and lm < d30:
                    st["bytes_older_30d"] += size
                if lm and lm >= now - timedelta(days=14):
                    st["by_day_bytes"][lm.strftime("%m-%d")] += size
                if size > st["largest"][1]:
                    st["largest"] = [v["Key"], size]
            else:
                st["noncurrent"] += 1
                st["noncurrent_bytes"] += size
                per_key[v["Key"]] += 1
        st["markers"] += len(res.get("DeleteMarkers", []))
        if not res.get("IsTruncated") or time.time() > deadline:
            st["truncated"] = bool(res.get("IsTruncated"))
            break
        token = {"KeyMarker": res["NextKeyMarker"], "VersionIdMarker": res.get("NextVersionIdMarker")}
    if per_key:
        st["max_versions_key"] = max(per_key.values())
        over = [(k, n) for k, n in per_key.items() if n > 10]
        st["keys_over_10"] = len(over)
        st["sample_over_10"] = sorted(over, key=lambda x: -x[1])[:5]
    st["by_day_bytes"] = dict(st["by_day_bytes"])
    return st


def main():
    s3 = boto3.client("s3", region_name=REGION, config=CFG)
    now = datetime.now(timezone.utc)
    with report("ops_6570_bucket_census") as r:
        r.heading("ops 6570 - full census of the live bucket by prefix (read-only)")
        prefixes = top_prefixes(s3)
        r.log("%d prefixes to walk" % len(prefixes))
        rows = []
        with cf.ThreadPoolExecutor(max_workers=16) as ex:
            for st in ex.map(lambda p: walk(p, now), prefixes):
                rows.append(st)
        tot = {k: sum(x[k] for x in rows) for k in ("current", "current_bytes", "noncurrent", "noncurrent_bytes", "markers", "calls")}
        r.log("bucket: %d current objects = %s GB; %d old versions = %s GB; %d delete markers; %d LIST calls; truncated prefixes: %s" % (
            tot["current"], gb(tot["current_bytes"]), tot["noncurrent"], gb(tot["noncurrent_bytes"]), tot["markers"], tot["calls"],
            [label(x["prefix"]) for x in rows if x.get("truncated")] or "none"))
        rows.sort(key=lambda x: -x["current_bytes"])
        r.log("prefix | current objects | current GB | older than 7 d GB | older than 30 d GB | old versions | old GB | max versions on a key | keys > 10 versions")
        for x in rows[:45]:
            r.log("- %s | %d | %s | %s | %s | %d | %s | %d | %d" % (
                label(x["prefix"]) or "(root files)", x["current"], gb(x["current_bytes"]), gb(x["bytes_older_7d"]), gb(x["bytes_older_30d"]),
                x["noncurrent"], gb(x["noncurrent_bytes"]), x["max_versions_key"], x["keys_over_10"]))
        over = [(label(x["prefix"]), x["keys_over_10"], x["sample_over_10"]) for x in rows if x["keys_over_10"]]
        r.log("prefixes with keys carrying more than 10 old versions: %s" % (
            [(p, n, [(k.split('/')[-1], c) for k, c in s]) for p, n, s in over] or "none"))
        # last-14-day write volume by day (current objects only) - the Monday spike
        by_day = defaultdict(int)
        for x in rows:
            for d, b in x["by_day_bytes"].items():
                by_day[d] += b
        r.log("bytes of today's current objects by the day they were written (last 14 d): %s" % ", ".join(
            "%s %s GB" % (d, gb(b)) for d, b in sorted(by_day.items())))
        big = sorted(((x["largest"][1], x["largest"][0]) for x in rows), reverse=True)[:8]
        r.log("largest objects: %s" % [(label(k), gb(b)) for b, k in big])
        stamp = now.strftime("%Y%m%dT%H%M%SZ")
        s3.put_object(Bucket=PRIVATE, Key="census/%s.json" % stamp, ServerSideEncryption="AES256",
                      Body=json.dumps({"at": now.isoformat(), "bucket": LIVE, "prefixes": rows}, default=str).encode())
        r.kv(current_objects=tot["current"], current_gb=gb(tot["current_bytes"]), old_versions=tot["noncurrent"], old_gb=gb(tot["noncurrent_bytes"]),
             prefixes=len(rows), census="s3://%s/census/%s.json" % (PRIVATE, stamp))
        r.ok("census complete")


if __name__ == "__main__":
    main()
