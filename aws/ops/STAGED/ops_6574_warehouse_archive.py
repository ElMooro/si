"""ops 6574 - piece 1 of the bucket design (Khalid, 2026-10-20): "never erased" - an archive copy with no delete path.

The census (ops 6570/6573) shows 434 GB / 1.28 M current objects spread over 239 prefixes - research stores, indexes,
archives, histories, private artifacts.  All of it is the warehouse; only the 751 top-level data/*.json files are
daily outputs an engine regenerates, and they are 0.6 GB.  So the archive takes the WHOLE bucket (one rule, no
prefix list to maintain or forget):

  * bucket justhodl-warehouse-archive-857687956942 (us-east-1): versioning on, SSE-S3, public access blocked,
    bucket owner enforced; lifecycle keeps the 3 newest old copies of a replicated file (a storm in the live bucket
    replicates 10 copies at most - the live rule - and leaves 3 here), aborts stray multipart uploads after 7 days
  * bucket policy: Deny s3:DeleteObject, s3:DeleteObjectVersion, s3:ReplicateDelete, s3:PutBucketVersioning,
    s3:PutLifecycleConfiguration, s3:PutBucketPolicy, s3:DeleteBucketPolicy, s3:DeleteBucket to EVERY principal except
    the account root - no Lambda role, no runner user, no replication role can delete or weaken it; only Khalid at the
    root user can (console)
  * IAM role justhodl-s3-replication-role (trusted by s3.amazonaws.com and batchoperations.s3.amazonaws.com) with the
    minimum replication rights on source objects and ReplicateObject/ReplicateTags on the archive
  * replication configuration on justhodl-dashboard-live: one rule, prefix '', Standard-IA at the destination,
    DeleteMarkerReplication Disabled - a deletion in the live bucket never reaches the archive
  * backfill of everything that exists today: an S3 Batch Replication job (manifest generated by S3, failures reported to
    the private bucket) - ~$14 one time (1.28 M objects x $0.01/1k IA PUT + $1.25/M + $0.25); launched by ops 6575 once
    the live bucket's new count rule has expired the storm versions (so they are not carried over first)
  * proof: a canary object written to the live bucket is awaited in the archive; a delete attempt on it with the
    runner's credentials must be AccessDenied

Idempotent: every step checks before it creates.  Nothing in the live bucket is changed except the replication
configuration and the canary object.
"""
from pathlib import Path
import json
import sys
import time

import boto3
from botocore.config import Config

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "aws" / "ops"))
from ops_report import report  # noqa: E402

REGION, ACCOUNT = "us-east-1", "857687956942"
LIVE, PRIVATE = "justhodl-dashboard-live", "justhodl-ops-private-%s" % ACCOUNT
ARCHIVE = "justhodl-warehouse-archive-%s" % ACCOUNT
ROLE = "justhodl-s3-replication-role"
CANARY = "_health/replication-canary.json"
CFG = Config(retries={"max_attempts": 10, "mode": "standard"}, connect_timeout=10, read_timeout=120)


def c(name):
    return boto3.client(name, region_name=REGION, config=CFG)


def sealed(s3):
    try:
        cur = json.loads(s3.get_bucket_policy(Bucket=ARCHIVE)["Policy"])
        return any(st.get("Sid") == "NoDeletePathExceptRoot" for st in cur.get("Statement", []))
    except s3.exceptions.ClientError:
        return False


def ensure_bucket(r, s3):
    try:
        s3.head_bucket(Bucket=ARCHIVE)
        r.log("archive bucket exists")
    except Exception:  # noqa: BLE001
        s3.create_bucket(Bucket=ARCHIVE)        # us-east-1: no LocationConstraint
        r.ok("archive bucket created: %s" % ARCHIVE)
    if sealed(s3):
        r.log("archive already sealed: settings left as they are (only the root user can change them)")
    else:
        s3.put_public_access_block(Bucket=ARCHIVE, PublicAccessBlockConfiguration={
            "BlockPublicAcls": True, "IgnorePublicAcls": True, "BlockPublicPolicy": True, "RestrictPublicBuckets": True})
        s3.put_bucket_ownership_controls(Bucket=ARCHIVE, OwnershipControls={"Rules": [{"ObjectOwnership": "BucketOwnerEnforced"}]})
        s3.put_bucket_encryption(Bucket=ARCHIVE, ServerSideEncryptionConfiguration={
            "Rules": [{"ApplyServerSideEncryptionByDefault": {"SSEAlgorithm": "AES256"}, "BucketKeyEnabled": False}]})
        s3.put_bucket_versioning(Bucket=ARCHIVE, VersioningConfiguration={"Status": "Enabled"})
        s3.put_bucket_lifecycle_configuration(Bucket=ARCHIVE, LifecycleConfiguration={"Rules": [
            {"ID": "archive-keep-3-old-copies", "Filter": {"Prefix": ""}, "Status": "Enabled",
             "NoncurrentVersionExpiration": {"NoncurrentDays": 1, "NewerNoncurrentVersions": 3},
             "AbortIncompleteMultipartUpload": {"DaysAfterInitiation": 7}}]})
        r.log("archive lifecycle: keep 3 old copies, abort stray uploads after 7 days")
    r.log("archive: versioning %s, public access blocked, SSE-S3" % s3.get_bucket_versioning(Bucket=ARCHIVE).get("Status"))


def seal_policy(r, s3):
    root = "arn:aws:iam::%s:root" % ACCOUNT
    policy = {"Version": "2012-10-17", "Statement": [
        {"Sid": "NoDeletePathExceptRoot", "Effect": "Deny", "Principal": "*",
         "Action": ["s3:DeleteObject", "s3:DeleteObjectVersion", "s3:ReplicateDelete", "s3:PutBucketVersioning",
                    "s3:PutLifecycleConfiguration", "s3:PutBucketPolicy", "s3:DeleteBucketPolicy", "s3:DeleteBucket",
                    "s3:PutBucketPublicAccessBlock"],
         "Resource": ["arn:aws:s3:::%s" % ARCHIVE, "arn:aws:s3:::%s/*" % ARCHIVE],
         "Condition": {"ArnNotEquals": {"aws:PrincipalArn": root}}}]}
    if sealed(s3):
        r.log("archive policy already sealed")
        return
    s3.put_bucket_policy(Bucket=ARCHIVE, Policy=json.dumps(policy))
    r.ok("archive policy sealed: deletes and weakening denied to everyone but the account root")


def ensure_role(r, iam):
    trust = {"Version": "2012-10-17", "Statement": [{"Effect": "Allow", "Principal": {"Service": ["s3.amazonaws.com", "batchoperations.s3.amazonaws.com"]},
                                                      "Action": "sts:AssumeRole"}]}
    try:
        arn = iam.get_role(RoleName=ROLE)["Role"]["Arn"]
        iam.update_assume_role_policy(RoleName=ROLE, PolicyDocument=json.dumps(trust))
        r.log("replication role exists")
    except iam.exceptions.NoSuchEntityException:
        arn = iam.create_role(RoleName=ROLE, AssumeRolePolicyDocument=json.dumps(trust),
                              Description="S3 replication + batch replication: justhodl-dashboard-live -> warehouse archive (ops 6574)")["Role"]["Arn"]
        r.ok("replication role created")
    doc = {"Version": "2012-10-17", "Statement": [
        {"Sid": "SourceBucket", "Effect": "Allow", "Action": ["s3:GetReplicationConfiguration", "s3:ListBucket", "s3:GetBucketVersioning",
                                                           "s3:PutInventoryConfiguration", "s3:InitiateReplication"],
         "Resource": "arn:aws:s3:::%s" % LIVE},
        {"Sid": "SourceObjects", "Effect": "Allow", "Action": ["s3:GetObjectVersionForReplication", "s3:GetObjectVersionAcl",
                                                            "s3:GetObjectVersionTagging", "s3:GetObjectRetention", "s3:GetObjectLegalHold",
                                                            "s3:InitiateReplication", "s3:GetObjectVersion"],
         "Resource": "arn:aws:s3:::%s/*" % LIVE},
        {"Sid": "ArchiveObjects", "Effect": "Allow", "Action": ["s3:ReplicateObject", "s3:ReplicateTags", "s3:ObjectOwnerOverrideToBucketOwner"],
         "Resource": "arn:aws:s3:::%s/*" % ARCHIVE},
        {"Sid": "BatchReports", "Effect": "Allow", "Action": ["s3:PutObject", "s3:GetObject", "s3:GetBucketLocation"],
         "Resource": ["arn:aws:s3:::%s/batch-replication/*" % PRIVATE, "arn:aws:s3:::%s" % PRIVATE]}]}
    iam.put_role_policy(RoleName=ROLE, PolicyName="justhodl-s3-replication", PolicyDocument=json.dumps(doc))
    return arn


def runner_grant(r, role_arn):
    """The runner user is at its per-user IAM quotas; new rights go through the group justhodl-runner-ecr (ops 5531)."""
    iam = c("iam")
    doc = {"Version": "2012-10-17", "Statement": [
        {"Sid": "PassReplicationRole", "Effect": "Allow", "Action": "iam:PassRole", "Resource": role_arn},
        {"Sid": "BatchReplicationJobs", "Effect": "Allow", "Action": ["s3:CreateJob", "s3:DescribeJob", "s3:ListJobs", "s3:UpdateJobStatus"], "Resource": "*"}]}
    name = "justhodl-runner-replication"
    arn = "arn:aws:iam::%s:policy/%s" % (ACCOUNT, name)
    try:
        iam.create_policy(PolicyName=name, PolicyDocument=json.dumps(doc), Description="ops 6574: pass the replication role, batch replication jobs")
    except iam.exceptions.EntityAlreadyExistsException:
        pass
    try:
        iam.attach_group_policy(GroupName="justhodl-runner-ecr", PolicyArn=arn)
        r.log("runner group: + %s (PassRole on the replication role, batch jobs)" % name)
    except Exception as ex:  # noqa: BLE001
        r.log("runner grant: %s" % type(ex).__name__)


def ensure_replication(r, s3, role_arn):
    want = {"Role": role_arn, "Rules": [{"ID": "warehouse-archive-all", "Priority": 1, "Status": "Enabled", "Filter": {"Prefix": ""},
                                         "DeleteMarkerReplication": {"Status": "Disabled"},
                                         "Destination": {"Bucket": "arn:aws:s3:::%s" % ARCHIVE, "StorageClass": "STANDARD_IA"}}]}
    try:
        cur = s3.get_bucket_replication(Bucket=LIVE)["ReplicationConfiguration"]
        if any(x.get("ID") == "warehouse-archive-all" and x.get("Status") == "Enabled" for x in cur.get("Rules", [])):
            r.log("replication rule already in place")
            return
    except s3.exceptions.ClientError:
        pass
    for attempt in range(8):   # the new role needs a moment to become assumable; PassRole may need a runner grant
        try:
            s3.put_bucket_replication(Bucket=LIVE, ReplicationConfiguration=want)
            break
        except s3.exceptions.ClientError as ex:
            code = ex.response["Error"]["Code"]
            if attempt == 7:
                raise
            if code == "AccessDenied" and attempt == 0:
                runner_grant(r, role_arn)
                time.sleep(45)
            else:
                r.log("replication put retry (%s)" % code)
                time.sleep(15)
    back = s3.get_bucket_replication(Bucket=LIVE)["ReplicationConfiguration"]
    rule = back["Rules"][0]
    r.ok("replication live: %s -> %s (%s), delete markers %s" % (LIVE, ARCHIVE, rule["Destination"].get("StorageClass"),
                                                                rule.get("DeleteMarkerReplication", {}).get("Status")))


def backfill_job(r, s3c, role_arn):
    """S3 Batch Replication for everything that exists today (new writes replicate on their own from now on)."""
    try:
        jobs = s3c.list_jobs(AccountId=ACCOUNT, JobStatuses=["Active", "Preparing", "Ready", "Suspended", "New"]).get("Jobs", [])
        for j in jobs:
            if (j.get("Description") or "").startswith("ops 6574 warehouse archive backfill"):
                r.log("backfill job already running: %s (%s)" % (j["JobId"], j["Status"]))
                return j["JobId"]
    except Exception as ex:  # noqa: BLE001
        r.log("list_jobs: %s" % type(ex).__name__)
    try:
        job = s3c.create_job(AccountId=ACCOUNT, ConfirmationRequired=False, Priority=10, RoleArn=role_arn,
                             Description="ops 6574 warehouse archive backfill (%s -> %s)" % (LIVE, ARCHIVE),
                             Operation={"S3ReplicateObject": {}},
                             Report={"Bucket": "arn:aws:s3:::%s" % PRIVATE, "Format": "Report_CSV_20180820", "Enabled": True,
                                     "Prefix": "batch-replication/reports", "ReportScope": "FailedTasksOnly"},
                             ManifestGenerator={"S3JobManifestGenerator": {
                                 "ExpectedBucketOwner": ACCOUNT, "SourceBucket": "arn:aws:s3:::%s" % LIVE, "EnableManifestOutput": False,
                                 "Filter": {"EligibleForReplication": True, "ObjectReplicationStatuses": ["NONE", "FAILED"]}}})
        r.ok("backfill job created: %s (S3 Batch Replication of every existing object; ops 6575 follows it)" % job["JobId"])
        return job["JobId"]
    except Exception as ex:  # noqa: BLE001
        if "AccessDenied" in str(ex) and not getattr(backfill_job, "retried", False):
            backfill_job.retried = True
            runner_grant(r, role_arn)
            time.sleep(45)
            return backfill_job(r, s3c, role_arn)
        r.warn("backfill job not created (%s: %s) - ongoing replication is live; the backfill needs a copier op" % (
            type(ex).__name__, str(ex)[:160]))
        return None


def canary(r, s3):
    body = json.dumps({"purpose": "replication canary (ops 6574)", "written_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}).encode()
    s3.put_object(Bucket=LIVE, Key=CANARY, Body=body, ContentType="application/json", CacheControl="no-cache")
    t0 = time.time()
    status = None
    while time.time() - t0 < 540:
        try:
            h = s3.head_object(Bucket=ARCHIVE, Key=CANARY)
            status = h.get("ReplicationStatus") or "REPLICA"
            break
        except s3.exceptions.ClientError:
            time.sleep(15)
    src = s3.head_object(Bucket=LIVE, Key=CANARY).get("ReplicationStatus")
    if status:
        r.ok("canary replicated in %d s (source status %s)" % (int(time.time() - t0), src))
        try:
            s3.delete_object(Bucket=ARCHIVE, Key=CANARY)
            r.fail("DELETE on the archive SUCCEEDED with the runner's credentials - the seal is not holding")
            return False
        except s3.exceptions.ClientError as ex:
            r.ok("delete attempt on the archive copy: %s (the seal holds)" % ex.response["Error"]["Code"])
            return True
    r.warn("canary not in the archive after 9 min (source status %s) - replication can take up to 15 min; ops 6575 re-checks" % src)
    return None


def main():
    s3, iam, s3c = c("s3"), c("iam"), c("s3control")
    with report("ops_6574_warehouse_archive") as r:
        r.heading("ops 6574 - warehouse archive: sealed bucket, replication of the whole live bucket, backfill, proof")
        ensure_bucket(r, s3)
        role_arn = ensure_role(r, iam)
        ensure_replication(r, s3, role_arn)
        seal_policy(r, s3)
        # backfill of the existing 1.28 M objects: ops 6575, once the live bucket's count rule has expired the storm
        # versions (a batch job started now could carry 573k old copies of one audit key into the archive first)
        proof = canary(r, s3)
        r.kv(archive=ARCHIVE, replication="enabled", backfill="ops 6575 (after the version cleanup)", canary_proof=proof, seal="deny Delete* except root")
        if proof is False:
            raise SystemExit(1)
        r.ok("archive in place")


if __name__ == "__main__":
    main()
