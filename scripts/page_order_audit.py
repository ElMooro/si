#!/usr/bin/env python3
"""scripts/page_order_audit.py - which public pages violate "most important first" (docs/ops/PAGE_ORDER.md)?

For every root *.html page (and page dirs with index.html), lists the top-level blocks (<section>/<header>/<article>
directly under <main>, or under <body> when there is no <main>) with their aria-label / h2, classifies each into the
seven tiers by the words in its label (a heuristic worklist, not a reorder), and reports the pages whose tier sequence
runs backwards (a later tier above an earlier one). Output: docs/ops/page-order-audit.md (regenerable; read-only).

    python3 scripts/page_order_audit.py            # writes the report
    python3 scripts/page_order_audit.py 13f.html   # one page, printed
"""
from pathlib import Path
import html as htmllib
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
TIERS = [
    (1, "verdict", r"verdict|stance|signal|alert|brief|heartbeat|what changed|summary|headline|call|today|now|regime|posture|score ?card|smart money|conviction|flows?\b|money"),
    (2, "breakdown", r"sector|industr|rotation|by class|asset class|bucket|breakdown|cohort|region|countr|curve|term structure|maturit"),
    (3, "boards", r"board|rank|top |most |leader|screen|list|table|watch|contender|movers|largest|widely"),
    (4, "roster", r"manager|drill|detail|roster|per |holdings|positions|portfolio|book|fund|ticker|symbol|name"),
    (5, "secondary", r"overlay|clone|option|commentary|divergence|ai |model|forecast|backtest|history|archive|chart"),
    (6, "provenance", r"source|evidence|method|reading|rules|glossary|limitation|master|provenance|how to read|notes|disclaimer|about|reproduce|identity"),
    (7, "operations", r"engine|schedule|health|observab|freshness|status|pipeline|run |ops|monitor|debug|diagnostic|telemetry|uptime"),
]
SKIP_DIRS = {"screener", "_partials", "node_modules", "_site", "aws", "tests", "scripts", "docs", "config", "data", "assets", "tools", "backups"}


def blocks(text):
    main = re.search(r"<main\b[^>]*>(.*?)</main>", text, re.S | re.I)
    body = main.group(1) if main else (re.search(r"<body\b[^>]*>(.*?)</body>", text, re.S | re.I) or [None, text])[1]
    out = []
    depth = 0
    for m in re.finditer(r"<(/?)(section|header|article)\b([^>]*)>", body, re.I):
        closing, tag, attrs = m.group(1), m.group(2).lower(), m.group(3)
        if closing:
            depth = max(0, depth - 1)
            continue
        if depth == 0:
            lab = re.search(r'aria-label="([^"]*)"', attrs)
            ident = re.search(r'id="([^"]*)"', attrs)
            after = body[m.end():m.end() + 4000]
            h = re.search(r"<h[12]\b[^>]*>(.*?)</h[12]>", after, re.S | re.I)
            title = htmllib.unescape(re.sub(r"<[^>]+>", "", h.group(1))).strip() if h else ""
            label = (lab.group(1) if lab else "") or title or (ident.group(1) if ident else tag)
            out.append({"tag": tag, "label": label[:80], "title": title[:80]})
        depth += 1
    return out


def tier_of(label):
    low = (label or "").lower()
    for n, name, pat in TIERS:
        if re.search(pat, low):
            return n, name
    return 0, "unclassified"


def audit_page(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    bl = blocks(text)
    rows = []
    for b in bl:
        n, name = tier_of(b["label"] + " " + b["title"])
        rows.append({**b, "tier": n, "tier_name": name})
    seq = [r["tier"] for r in rows if r["tier"]]
    inversions = sum(1 for i in range(1, len(seq)) if seq[i] < max(seq[:i]))
    return rows, inversions


def pages():
    for p in sorted(ROOT.glob("*.html")) + sorted(ROOT.glob("*/index.html")):
        rel = p.relative_to(ROOT)
        if rel.parts[0] in SKIP_DIRS or rel.name.startswith("_"):
            continue
        yield p


def main(argv):
    if len(argv) > 1:
        rows, inv = audit_page(ROOT / argv[1])
        for r in rows:
            print("%d %-12s %s" % (r["tier"], r["tier_name"], r["label"]))
        print("inversions:", inv)
        return 0
    lines = ["# Page order audit (generated by scripts/page_order_audit.py - a worklist, not a reorder)", "",
             "Tiers: 1 verdict, 2 breakdown, 3 boards, 4 roster, 5 secondary, 6 provenance, 7 operations (docs/ops/PAGE_ORDER.md). ",
             "An inversion is a block whose tier is lower than a block above it. Labels are heuristically tiered from their words; a page with 0 inversions may still deserve a human look.", ""]
    summary = []
    for p in pages():
        rows, inv = audit_page(p)
        if len(rows) < 3:
            continue
        summary.append((inv, str(p.relative_to(ROOT)), rows))
    summary.sort(key=lambda t: (-t[0], t[1]))
    lines.append("| page | blocks | inversions | tier sequence |")
    lines.append("|---|---|---|---|")
    for inv, rel, rows in summary:
        lines.append("| `%s` | %d | %d | %s |" % (rel, len(rows), inv, " ".join(str(r["tier"]) for r in rows)))
    lines.append("")
    lines.append("## Pages with inversions - the blocks, in served order")
    for inv, rel, rows in summary:
        if not inv:
            continue
        lines.append("")
        lines.append("### `%s` (%d inversions)" % (rel, inv))
        for r in rows:
            lines.append("- tier %d %s - %s" % (r["tier"], r["tier_name"], r["label"]))
    out = ROOT / "docs" / "ops" / "page-order-audit.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    n_inv = sum(1 for inv, _, _ in summary if inv)
    print("page order audit: %d pages with 3+ blocks, %d with inversions -> %s" % (len(summary), n_inv, out.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
