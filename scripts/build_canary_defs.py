#!/usr/bin/env python3
"""The canaries' definitions, read from the engines that own them, written for the engine that tests them.

    python3 scripts/build_canary_defs.py            write aws/lambdas/justhodl-warroom-weights/source/canary_defs.json
    python3 scripts/build_canary_defs.py --check    exit 1 if the kept file is not what the engines say today

The macro grid's SIGNALS (justhodl-canary-grid) and the plumbing aggregator's INDICATORS (justhodl-plumbing-aggregator)
are read as literals, never imported; the war room's PLUMBING_DEDUPE says which plumbing rows do not vote there.
A deployment test runs --check, so the record can never test a rule the engines have since changed.
"""
import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GRID = ROOT / "aws/lambdas/justhodl-canary-grid/source/lambda_function.py"
PLUMB = ROOT / "aws/lambdas/justhodl-plumbing-aggregator/source/lambda_function.py"
WARROOM = ROOT / "aws/lambdas/justhodl-canary-warroom/source/lambda_function.py"
OUT = ROOT / "aws/lambdas/justhodl-warroom-weights/source/canary_defs.json"


def literal(path, name):
    for node in ast.parse(path.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == name:
            v = node.value
            if isinstance(v, ast.List):
                return [({k.arg: ast.literal_eval(k.value) for k in el.keywords} if isinstance(el, ast.Call) else ast.literal_eval(el)) for el in v.elts]
            return ast.literal_eval(v)
    raise SystemExit("%s: no %s" % (path, name))


def build():
    grid = []
    for s in literal(GRID, "SIGNALS"):
        src = s["fred"] if isinstance(s["fred"], list) else [s["fred"]]
        grid.append({"key": s["key"], "name": s["name"], "grid": s["grid"], "sources": src, "kind": s["kind"], "win": s.get("win"),
                     "dir": s["dir"], "lead": s.get("lead"), "limit": s["limit"]})
    dedupe = set(literal(WARROOM, "PLUMBING_DEDUPE"))
    plumb = [{"id": p["id"], "label": p["label"], "layer": p.get("layer"), "polarity": p.get("polarity", 1), "source": p.get("source"),
              "deduped": p["id"] in dedupe} for p in literal(PLUMB, "INDICATORS")]
    return {"note": "Generated by scripts/build_canary_defs.py from the engines' own sources. Do not edit by hand.",
            "from": [str(GRID.relative_to(ROOT)), str(PLUMB.relative_to(ROOT)), str(WARROOM.relative_to(ROOT))], "grid": grid, "plumbing": plumb}


def main():
    text = json.dumps(build(), indent=1, ensure_ascii=False, sort_keys=True) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("canary_defs.json is not what the engines say today: run python3 scripts/build_canary_defs.py")
            return 1
        print("canary_defs.json matches the engines (%d grid, %d plumbing)" % (text.count('"kind"'), text.count('"polarity"')))
        return 0
    OUT.write_text(text, encoding="utf-8")
    print("wrote %s" % OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
